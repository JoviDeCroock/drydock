import { createHash } from "node:crypto";
import { describe, expect, test } from "vitest";
import {
  diffLockfileChanges,
  parseLockfile,
  PUBLIC_ROUTE,
  routedBump,
} from "../server/lib/dependency-review/lockfiles";
import type { DependencyBump, LockfileKind } from "../server/lib/dependency-review/types";

const sha512 = (seed: string) => `sha512-${createHash("sha512").update(seed).digest("base64")}`;
const sha256 = (seed: string) => `sha256:${createHash("sha256").update(seed).digest("hex")}`;

// Every edge an entry installs must name an entry of the same lockfile; one
// that names nothing is resolved by the installer, so the lockfile is not the
// whole install and reads as unread coverage.
describe("an install edge that resolves to no entry makes the lockfile incomplete", () => {
  describe("Yarn classic", () => {
    const stanza = (descriptors: string, version: string, deps: Record<string, string> = {}) =>
      [
        `${descriptors}:`,
        `  version "${version}"`,
        `  resolved "https://registry.yarnpkg.com/${descriptors.split("@")[0]}/-/x-${version}.tgz"`,
        `  integrity ${sha512(descriptors + version)}`,
        ...(Object.keys(deps).length > 0
          ? ["  dependencies:", ...Object.entries(deps).map(([d, r]) => `    ${d} "${r}"`)]
          : []),
        "",
      ].join("\n");
    const lock = (...stanzas: string[]) =>
      [
        "# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.",
        "# yarn lockfile v1",
        "",
        "",
        ...stanzas,
      ].join("\n");

    test("the reviewer's input: host declares payload, and no stanza locks it", () => {
      const head = parseLockfile(
        "yarn",
        lock(stanza("host@^1.0.0", "1.0.1", { payload: "^1.0.0" })),
      );
      expect(head.complete).toBe(false);
      expect(head.unresolvedEdges).toEqual(["host@^1.0.0 → payload@^1.0.0"]);
      const base = parseLockfile("yarn", lock(stanza("host@^1.0.0", "1.0.0")));
      expect(diffLockfileChanges(base, head, "yarn.lock")).toEqual([]);
    });

    test("an edge names the exact pattern; a stanza for another range does not count", () => {
      const locked = lock(
        stanza("host@^1.0.0", "1.0.1", { payload: "^1.0.0" }),
        stanza("payload@^1.0.0, payload@^1.1.0", "1.1.0"),
      );
      expect(parseLockfile("yarn", locked).complete).toBe(true);
      const other = lock(
        stanza("host@^1.0.0", "1.0.1", { payload: "^1.0.0" }),
        stanza("payload@^2.0.0", "2.0.0"),
      );
      expect(parseLockfile("yarn", other).complete).toBe(false);
    });
  });

  describe("Yarn Berry", () => {
    const entry = (descriptor: string, resolution: string, deps: Record<string, string> = {}) =>
      [
        `"${descriptor}":`,
        `  version: ${resolution.split("@npm:")[1]}`,
        `  resolution: "${resolution}"`,
        ...(Object.keys(deps).length > 0
          ? ["  dependencies:", ...Object.entries(deps).map(([d, r]) => `    ${d}: "${r}"`)]
          : []),
        "  checksum: 10/abc",
        "  languageName: node",
        "  linkType: hard",
        "",
      ].join("\n");
    const lock = (...entries: string[]) =>
      ["__metadata:", "  version: 8", "  cacheKey: 10", "", ...entries].join("\n");
    const remark = lock(
      entry("remark-parse@npm:^8.0.0", "remark-parse@npm:8.0.3", { trim: "npm:0.0.1" }),
      entry("trim@npm:1.0.1", "trim@npm:1.0.1"),
    );

    test("a dependency with no entry for its descriptor", () => {
      const snapshot = parseLockfile("yarn", remark);
      expect(snapshot.complete).toBe(false);
      expect(snapshot.unresolvedEdges).toEqual(["remark-parse@npm:^8.0.0 → trim@npm:0.0.1"]);
    });

    test("the root manifest's `resolutions` redirect an edge to the entry it locks", () => {
      // 24 of the 36 real Berry lockfiles in the replay corpus have exactly
      // this edge, redirected by `"resolutions": {"trim": "1.0.1"}`.
      for (const key of ["trim", "remark-parse/trim", "trim@0.0.1", "**/trim"]) {
        const manifestText = JSON.stringify({ resolutions: { [key]: "1.0.1" } });
        expect(parseLockfile("yarn", remark, { manifestText }).complete).toBe(true);
      }
      // A redirect to a descriptor the lockfile does not lock resolves nothing.
      const elsewhere = JSON.stringify({ resolutions: { trim: "2.0.0" } });
      expect(parseLockfile("yarn", remark, { manifestText: elsewhere }).complete).toBe(false);
    });
  });

  describe("package-lock.json", () => {
    const lock = (packages: Record<string, unknown>) =>
      JSON.stringify({ lockfileVersion: 3, packages: { "": {}, ...packages } });
    const at = (name: string, version: string, extra: Record<string, unknown> = {}) => ({
      version,
      resolved: `https://registry.npmjs.org/${name}/-/${name}-${version}.tgz`,
      integrity: sha512(`${name}@${version}`),
      ...extra,
    });

    test("an edge Node's lookup from the entry's path cannot find", () => {
      const snapshot = parseLockfile(
        "npm",
        lock({ "node_modules/host": at("host", "1.0.1", { dependencies: { payload: "^1" } }) }),
      );
      expect(snapshot.complete).toBe(false);
      expect(snapshot.unresolvedEdges).toEqual(["node_modules/host → payload@^1"]);
    });

    test("nested, hoisted, workspace, and optional-peer edges resolve", () => {
      const snapshot = parseLockfile(
        "npm",
        lock({
          "packages/app": { dependencies: { host: "^1" }, devDependencies: { ms: "^2" } },
          "node_modules/app": { resolved: "packages/app", link: true },
          "node_modules/host": at("host", "1.0.1", {
            dependencies: { debug: "^4", ms: "^2" },
            peerDependencies: { react: "*" },
            peerDependenciesMeta: { react: { optional: true } },
          }),
          "node_modules/host/node_modules/debug": at("debug", "4.0.0", {
            dependencies: { ms: "^2" },
          }),
          "node_modules/ms": at("ms", "2.1.3"),
        }),
      );
      expect(snapshot.complete).toBe(true);
      expect(snapshot.unresolvedEdges).toBeUndefined();
    });

    test("a missing peer is left to the repository's legacy-peer-deps setting", () => {
      const snapshot = parseLockfile(
        "npm",
        lock({
          "node_modules/acorn-jsx": at("acorn-jsx", "5.3.2", { peerDependencies: { acorn: "^8" } }),
        }),
      );
      expect(snapshot.complete).toBe(true);
      expect(snapshot.unresolvedPeerEdges).toEqual(["node_modules/acorn-jsx → acorn@^8"]);
    });
  });

  describe("pnpm-lock.yaml", () => {
    const v9 = (snapshots: string[], packages: string[], importer: string[] = []) =>
      [
        "lockfileVersion: '9.0'",
        "",
        "importers:",
        "",
        "  .:",
        ...(importer.length > 0 ? ["    dependencies:", ...importer] : []),
        "",
        "packages:",
        "",
        ...packages,
        "",
        "snapshots:",
        "",
        ...snapshots,
      ].join("\n");
    const pkg = (key: string) => [`  ${key}:`, `    resolution: {integrity: ${sha512(key)}}`, ""];

    test("a snapshot dependency naming no key", () => {
      const snapshot = parseLockfile(
        "pnpm",
        v9(["  host@1.0.1:", "    dependencies:", "      payload: 1.0.0", ""], pkg("host@1.0.1")),
      );
      expect(snapshot.complete).toBe(false);
      expect(snapshot.unresolvedEdges).toEqual(["host@1.0.1 → payload@1.0.0"]);
    });

    test("versions with peer suffixes, aliases, and links resolve", () => {
      const snapshot = parseLockfile(
        "pnpm",
        v9(
          [
            "  host@1.0.1(react@18.0.0):",
            "    dependencies:",
            "      dep: 2.0.0(react@18.0.0)",
            "      innocent: real@3.0.0",
            "      local: link:../local",
            "",
            "  dep@2.0.0(react@18.0.0): {}",
            "",
            "  real@3.0.0: {}",
            "",
            "  react@18.0.0: {}",
            "",
          ],
          [...pkg("host@1.0.1"), ...pkg("dep@2.0.0"), ...pkg("real@3.0.0"), ...pkg("react@18.0.0")],
          ["      host:", "        specifier: ^1.0.0", "        version: 1.0.1(react@18.0.0)"],
        ),
      );
      expect(snapshot.unresolvedEdges).toBeUndefined();
      expect(snapshot.complete).toBe(true);
    });

    test("an importer edge naming no key", () => {
      const snapshot = parseLockfile(
        "pnpm",
        v9([], [], ["      payload:", "        specifier: ^1.0.0", "        version: 1.0.0"]),
      );
      expect(snapshot.unresolvedEdges).toEqual([". → payload@1.0.0"]);
    });

    test("v6 and v5 keys", () => {
      const v6 = [
        "lockfileVersion: '6.0'",
        "",
        "packages:",
        "",
        "  /host@1.0.1:",
        `    resolution: {integrity: ${sha512("h")}}`,
        "    dependencies:",
        "      dep: 2.0.0",
        "      innocent: /real@3.0.0",
        "",
        "  /dep@2.0.0:",
        `    resolution: {integrity: ${sha512("d")}}`,
        "",
        "  /real@3.0.0:",
        `    resolution: {integrity: ${sha512("r")}}`,
        "",
      ].join("\n");
      expect(parseLockfile("pnpm", v6).complete).toBe(true);
      expect(parseLockfile("pnpm", v6.replace("dep: 2.0.0", "dep: 2.0.1")).complete).toBe(false);
      const v5 = [
        "lockfileVersion: 5.4",
        "",
        "packages:",
        "",
        "  /host/1.0.1:",
        `    resolution: {integrity: ${sha512("h")}}`,
        "    dependencies:",
        "      dep: 2.0.0_react@18.0.0",
        "",
        "  /dep/2.0.0_react@18.0.0:",
        `    resolution: {integrity: ${sha512("d")}}`,
        "",
      ].join("\n");
      expect(parseLockfile("pnpm", v5).complete).toBe(true);
      expect(parseLockfile("pnpm", v5.replace("dep: 2.0.0_", "dep: 2.0.1_")).complete).toBe(false);
    });
  });

  describe("uv.lock", () => {
    const pkg = (name: string, lines: string[] = []) => [
      "",
      "[[package]]",
      `name = "${name}"`,
      'version = "1.0.0"',
      'source = { registry = "https://pypi.org/simple" }',
      ...lines,
      `sdist = { url = "https://files.pythonhosted.org/packages/ab/${name}.tar.gz", hash = "${sha256(name)}", size = 1 }`,
    ];
    const lock = (...packages: string[][]) => ["version = 1", ...packages.flat()].join("\n");

    test("a dependency, optional group, or dev group naming no package", () => {
      const deps = lock(pkg("host", ["dependencies = [", '    { name = "payload" },', "]"]));
      expect(parseLockfile("uv", deps).unresolvedEdges).toEqual(["host → payload@"]);
      const inline = lock(pkg("host", ['dependencies = [{ name = "payload" }]']));
      expect(parseLockfile("uv", inline).complete).toBe(false);
      for (const table of ["optional-dependencies", "dev-dependencies"]) {
        const group = ["", `[package.${table}]`, "socks = [", '    { name = "Pay_Load" },', "]"];
        expect(parseLockfile("uv", lock(pkg("host"), group)).complete).toBe(false);
        // Names compare normalized: `Pay_Load` is `pay-load`.
        expect(parseLockfile("uv", lock(pkg("pay-load"), pkg("host"), group)).complete).toBe(true);
      }
    });

    test("what a package declared in its metadata is not an install edge", () => {
      const declared = lock(pkg("host"), [
        "",
        "[package.metadata]",
        'requires-dist = [{ name = "payload", marker = "extra == \'x\'" }]',
      ]);
      expect(parseLockfile("uv", declared).complete).toBe(true);
    });
  });
});

describe("a bundled base copy is no predecessor of a copy the head fetches", () => {
  const lock = (packages: Record<string, unknown>) =>
    JSON.stringify({ lockfileVersion: 3, packages: { "": {}, ...packages } });
  const fetched = (name: string, version: string) => ({
    version,
    resolved: `https://registry.npmjs.org/${name}/-/${name}-${version}.tgz`,
    integrity: sha512(`${name}@${version}`),
  });
  const bundler = (payload: string) => ({
    "node_modules/bundler": { ...fetched("bundler", "1.0.0"), bundleDependencies: ["payload"] },
    "node_modules/bundler/node_modules/payload": { version: payload, inBundle: true },
  });
  const changes = (before: Record<string, unknown>, after: Record<string, unknown>) =>
    diffLockfileChanges(parseLockfile("npm", lock(before)), parseLockfile("npm", lock(after)), "l");
  const routed = (before: Record<string, unknown>, after: Record<string, unknown>) =>
    changes(before, after).map((change): DependencyBump =>
      routedBump(change, PUBLIC_ROUTE, {
        publicMirrors: [],
        privateRegistries: [],
        privateScopes: [],
      }),
    );
  const payloadOf = (bumps: DependencyBump[]) => bumps.find((bump) => bump.name === "payload");

  test("the same version fetched at the head is new to the lockfile, not a re-pin", () => {
    const bumps = routed(
      { ...bundler("1.0.0"), "node_modules/host": fetched("host", "1.0.0") },
      {
        ...bundler("1.0.0"),
        "node_modules/host": fetched("host", "1.0.1"),
        "node_modules/payload": fetched("payload", "1.0.0"),
      },
    );
    expect(payloadOf(bumps)).toEqual({
      ecosystem: "npm",
      name: "payload",
      fromVersion: null,
      toVersion: "1.0.0",
      direct: false,
      lockfilePath: "l",
      pinnedHashes: [sha512("payload@1.0.0")],
    });
  });

  test("an unpublished bundled version is no predecessor of the public release", () => {
    const bumps = routed(bundler("0.0.0-internal"), {
      ...bundler("0.0.0-internal"),
      "node_modules/payload": fetched("payload", "1.0.0"),
    });
    expect(payloadOf(bumps)).toMatchObject({ fromVersion: null, toVersion: "1.0.0" });
    expect(payloadOf(bumps)).not.toHaveProperty("repinned");
  });

  test("a bundled copy whose version changes, still only bundled, stays an ordinary bump", () => {
    const bumps = routed(bundler("1.0.0"), bundler("1.0.1"));
    expect(payloadOf(bumps)).toMatchObject({ fromVersion: "1.0.0", toVersion: "1.0.1" });
  });

  test("a bundled copy added beside a registry copy of the same release changes nothing", () => {
    const registry = { "node_modules/payload": fetched("payload", "1.0.0") };
    expect(payloadOf(routed(registry, { ...registry, ...bundler("1.0.0") }))).toBeUndefined();
  });
});

describe("lockfile kinds the edge check does not apply to", () => {
  test.each<[LockfileKind, string]>([["requirements", "host==1.0.0\n"]])(
    "%s records no edges",
    (kind, text) => {
      expect(parseLockfile(kind, text).unresolvedEdges).toBeUndefined();
    },
  );
});
