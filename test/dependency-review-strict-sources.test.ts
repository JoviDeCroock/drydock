describe("the strict YAML reader agrees with a YAML parser on everything it accepts", () => {
  // Builds the tree the reader's entries describe, with scalars as strings,
  // the shape `yaml`'s failsafe schema yields.
  function strictTree(text: string): unknown[] | null {
    const docs: unknown[] = [];
    let root: Record<string, unknown> | unknown[] | null = null;
    // The block value each depth's entries go into, created on first use.
    let open: Array<{ parent: Record<string, unknown> | unknown[]; key: string | number }> = [];
    const put = (
      parent: Record<string, unknown> | unknown[],
      key: string | number,
      value: unknown,
    ) =>
      Object.defineProperty(parent, key, {
        value,
        enumerable: true,
        writable: true,
        configurable: true,
      });
    const ok = readStrictYaml(text, (entry) => {
      if (entry === null) {
        if (root !== null) docs.push(root);
        root = null;
        open = [];
        return;
      }
      const { depth, key, value } = entry;
      let container: Record<string, unknown> | unknown[];
      if (depth === 0) {
        root ??= key === null ? [] : {};
        container = root;
      } else {
        const holder = open[depth - 1];
        const current = (holder.parent as Record<string | number, unknown>)[holder.key];
        if (current === "") {
          container = key === null ? [] : {};
          put(holder.parent, holder.key, container);
        } else {
          container = current as Record<string, unknown> | unknown[];
        }
      }
      const slot = key === null ? (container as unknown[]).length : key;
      const js =
        value.kind === "block"
          ? ""
          : value.kind === "scalar"
            ? value.text
            : value.kind === "seq"
              ? [...value.items]
              : Object.fromEntries(value.fields);
      put(container, slot, js);
      open.length = depth;
      open[depth] = { parent: container, key: slot };
    });
    if (!ok) return null;
    if (root !== null) docs.push(root);
    return docs;
  }

  function yamlTree(text: string): unknown[] | "error" {
    const docs = parseAllDocuments(text, { schema: "failsafe", uniqueKeys: true });
    if (!Array.isArray(docs) || docs.some((doc) => doc.errors.length > 0)) return "error";
    return docs.map((doc) => doc.toJS()).filter((doc) => doc !== null && doc !== undefined);
  }

  const documents = [
    pnpm([
      "  '@scope/a@1.0.0':",
      `    resolution: {integrity: ${sha512("a")}}`,
      "    engines: {node: '>=18'}",
      "    cpu: [x64, arm64]",
      "",
      "  b@https://codeload.github.com/a/b/tar.gz/abc:",
      "    resolution: {tarball: https://codeload.github.com/a/b/tar.gz/abc}",
      "    version: 1.0.0",
      "    deprecated: It''s old",
      "    bundledDependencies:",
      "      - x",
      "      - y",
    ]),
    [
      "---",
      "lockfileVersion: '9.0'",
      "importers:",
      "  .:",
      "    configDependencies: {}",
      "---",
      "a: b",
    ].join("\n"),
    [
      "packages:",
      '  "foo@1.0.0":',
      "    resolution:",
      "      {",
      "        integrity: sha512-x,",
      '        tarball: "https://x/y, z",',
      "      }",
      '    engines: { node: ">=6.9.0" }',
    ].join("\n"),
    berry([
      '"foo@npm:^1.0.0, foo@npm:^1.1.0":',
      "  version: 1.1.0",
      '  resolution: "foo@npm:1.1.0"',
      "  dependencies:",
      '    "@scope/bar": "npm:^2.0.0"',
      "  dependenciesMeta:",
      "    fsevents:",
      "      optional: true",
      "  conditions: os=darwin & cpu=arm64",
      "  checksum: 10c0/abc",
    ]),
    "a: {b: 'c, d', 'e''f': g}\nh: [i, 'j, k']\nl: x:y\nm: https://x/#y",
    // Hostile shapes: each is either refused or read the way a YAML parser reads it.
    "a: &x b\nc: *x",
    "a: !!str b",
    "? a\n: b",
    "a: |\n  b",
    "a: b\n  c",
    'a: "b\\x20c"',
    "a:\n    b: c",
    "a: b # c",
    "a: 'b\nc'",
    "<<: {a: b}",
    "a: {b: {c: d}}",
    "a: [b, [c]]",
    "a: b\na: c",
    "- a\nb: c",
    "a:\n  - b: c",
    "a: {b: c,}",
    "a: { b: c }",
    "a: b:",
    "a: -b",
    "a: 'b'c",
    "a:  b",
    "'a'b: c",
    "a : b",
    "a\u2028b: c",
    "a: b\r c: d",
    "\ufeffa: b",
    "a: {'b': c, \"d\": 'e'}",
    "a: ['b, c', \"d\"]",
    "a: b'c\nd: e\"f",
    "a: {b: c'd}",
    "...\na: b",
  ];

  test.each(documents.map((text) => [text]))("%j", (text) => {
    const ours = strictTree(text);
    if (ours === null) return;
    expect(ours).toEqual(yamlTree(text));
  });

  test("the canonical documents are all accepted", () => {
    for (const text of documents.slice(0, 5)) expect(strictTree(text), text).not.toBeNull();
  });
});

